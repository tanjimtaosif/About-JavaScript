//  Assignment Operators
//  = 
// += 
// -= 
// *= 
// /= 
// %=

let a = 12;
console.log("Initial value:", a); // 12

// 1. Addition Assignment (+=)
a += 3; // Same as: a = a + 3
console.log("After += 3:", a);   // 15

// 2. Subtraction Assignment (-=)
a -= 11; // Same as: a = a - 11
console.log("After -= 11:", a);  // 4

// 3. Multiplication Assignment (*=)
a *= 2; // Same as: a = a * 2
console.log("After *= 2:", a);   // 8

// 4. Division Assignment (/=)
a /= 2; // Same as: a = a / 2
console.log("After /= 2:", a);   // 4

// 5. Remainder Assignment (%=)
a %= 3; // Same as: a = a % 3 (4 divided by 3 has a remainder of 1)
console.log("After %= 3:", a);   // 1
